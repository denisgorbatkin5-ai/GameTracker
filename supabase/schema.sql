create or replace function public.profile_collection(p_username text)
returns setof jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'id', ci.id,
    'status', ci.status,
    'rating', ci.rating,
    'hours_played', ci.hours_played,
    'is_favorite', ci.is_favorite,
    'finished_at', ci.finished_at,
    'created_at', ci.created_at,
    'updated_at', ci.updated_at,
    'game', jsonb_build_object(
      'id', g.id,
      'steam_appid', g.steam_appid,
      'name', g.name,
      'header_image', g.header_image,
      'capsule_image', g.capsule_image,
      'background_image', g.background_image,
      'genres', g.genres
    )
  )
  from public.collection_items ci
  join public.games g on g.id = ci.game_id
  join public.profiles p on p.id = ci.user_id
  where lower(p.username) = lower(p_username)
    and public.can_view_profile(ci.user_id)
  order by ci.updated_at desc;
$$;

revoke all on function public.profile_collection(text) from public;
grant execute on function public.profile_collection(text) to anon, authenticated;

create or replace function public.profile_showcase_games(p_username text)
returns setof jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'user_id', s.user_id,
    'game_id', s.game_id,
    'position', s.position,
    'game', jsonb_build_object(
      'id', g.id,
      'steam_appid', g.steam_appid,
      'name', g.name,
      'header_image', g.header_image,
      'capsule_image', g.capsule_image,
      'genres', g.genres,
      'release_date', g.release_date
    )
  )
  from public.profile_showcase s
  join public.games g on g.id = s.game_id
  join public.profiles p on p.id = s.user_id
  where lower(p.username) = lower(p_username)
    and public.can_view_profile(s.user_id)
  order by s.position asc;
$$;

revoke all on function public.profile_showcase_games(text) from public;
grant execute on function public.profile_showcase_games(text) to anon, authenticated;


