-- auto-create a profile whenever a new auth user signs up
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  base      text;
  candidate text;
  suffix    int := 0;
begin
  base := coalesce(
    nullif(trim(new.raw_user_meta_data ->> 'username'), ''),
    split_part(coalesce(new.email, 'player'), '@', 1),
    'player'
  );
  base := regexp_replace(base, '[^A-Za-z0-9_]', '', 'g');
  if length(base) < 3 then
    base := base || 'player';
  end if;
  base := left(base, 16);

  candidate := base;
  while exists (select 1 from public.profiles where lower(username) = lower(candidate)) loop
    suffix := suffix + 1;
    candidate := left(base, 20 - length(suffix::text)) || suffix::text;
  end loop;

  insert into public.profiles (id, username, display_name)
  values (new.id, candidate, candidate);

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- --------------------------------------------------------- upsert helper
create or replace function public.upsert_games(rows jsonb)
returns setof public.games
language plpgsql
security definer
set search_path = public
as $$
begin
  -- RETURN QUERY is required: a bare INSERT ... RETURNING discards its rows in PL/pgSQL.
  return query
  insert into public.games (
    steam_appid, name, header_image, background_image, capsule_image, library_image,
    release_date, developers, publishers, genres, platforms,
    short_description, metacritic, price
  )
  select
    (item ->> 'steam_appid')::bigint,
    coalesce(nullif(item ->> 'name', ''), 'Unknown'),
    item ->> 'header_image',
    item ->> 'background_image',
    item ->> 'capsule_image',
    item ->> 'library_image',
    nullif(item ->> 'release_date', '')::date,
    coalesce(array(select jsonb_array_elements_text(coalesce(item -> 'developers', '[]'::jsonb))), '{}'),
    coalesce(array(select jsonb_array_elements_text(coalesce(item -> 'publishers', '[]'::jsonb))), '{}'),
    coalesce(array(select jsonb_array_elements_text(coalesce(item -> 'genres', '[]'::jsonb))), '{}'),
    coalesce(array(select jsonb_array_elements_text(coalesce(item -> 'platforms', '[]'::jsonb))), '{}'),
    coalesce(item ->> 'short_description', ''),
    nullif(item ->> 'metacritic', '')::int,
    nullif(item ->> 'price', '')
  from jsonb_array_elements(rows) as item
  on conflict (steam_appid) do update set
    name              = excluded.name,
    header_image      = excluded.header_image,
    background_image  = excluded.background_image,
    capsule_image     = excluded.capsule_image,
    library_image     = excluded.library_image,
    release_date      = excluded.release_date,
    developers        = excluded.developers,
    publishers        = excluded.publishers,
    genres            = excluded.genres,
    platforms         = excluded.platforms,
    short_description = excluded.short_description,
    metacritic        = excluded.metacritic,
    price             = excluded.price,
    updated_at        = now()
  returning *;
end;
$$;

revoke all on function public.upsert_games(jsonb) from public;
grant execute on function public.upsert_games(jsonb) to anon, authenticated;

-- tier list save (replace rows + items atomically)
create or replace function public.save_tier_list(
  p_tier_list_id bigint,
  p_rows jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  row_data jsonb;
  new_row_id bigint;
begin
  if not exists (
    select 1 from public.tier_lists
    where id = p_tier_list_id and user_id = auth.uid()
  ) then
    raise exception 'not your tier list';
  end if;

  delete from public.tier_rows where tier_list_id = p_tier_list_id;

  for row_data in select * from jsonb_array_elements(p_rows)
  loop
    insert into public.tier_rows (tier_list_id, key, label, color, sort_order)
    values (
      p_tier_list_id,
      coalesce(row_data ->> 'key', 'row'),
      coalesce(row_data ->> 'label', 'Row'),
      coalesce(row_data ->> 'color', '#64748b'),
      coalesce((row_data ->> 'sort_order')::int, 0)
    )
    returning id into new_row_id;

    insert into public.tier_items (tier_row_id, game_id, position)
    select new_row_id, (entry ->> 'game_id')::bigint, (entry ->> 'position')::int
    from jsonb_array_elements(coalesce(row_data -> 'items', '[]'::jsonb)) as entry
    where exists (select 1 from public.games where id = (entry ->> 'game_id')::bigint);
  end loop;

  update public.tier_lists set updated_at = now() where id = p_tier_list_id;
end;
$$;

grant execute on function public.save_tier_list(bigint, jsonb) to authenticated;

-- ------------------------------------------------------------ friends
-- Visibility rule used by every "someone else's data" path: public profile,
-- the owner, or an accepted friend.
create or replace function public.can_view_profile(p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = p_user_id
      and (
        p.is_public
        or p.id = auth.uid()
        or exists (
          select 1 from public.friendships f
          where f.status = 'accepted'
            and (
              (f.user_id = auth.uid() and f.friend_id = p_user_id)
              or (f.friend_id = auth.uid() and f.user_id = p_user_id)
            )
        )
      )
  );
$$;

revoke all on function public.can_view_profile(uuid) from public;
grant execute on function public.can_view_profile(uuid) to anon, authenticated;

-- Nickname availability for the signup form. Existence of a nickname is implied by it
-- being a unique public identifier, so leaking a boolean here is not a real disclosure.
create or replace function public.username_available(p_username text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select trim(coalesce(p_username, '')) ~ '^[A-Za-z0-9_]{3,20}$'
     and not exists (
       select 1 from public.profiles where lower(username) = lower(trim(p_username))
     );
$$;

revoke all on function public.username_available(text) from public;
grant execute on function public.username_available(text) to anon, authenticated;

-- Sends (or auto-accepts) a friend request. Returns a short status for the UI.
create or replace function public.add_friend(p_username text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  target   uuid;
  existing text;
begin
  if auth.uid() is null then
    return 'unauthorized';
  end if;

  select id into target from public.profiles where lower(username) = lower(p_username);
  if target is null then return 'not_found'; end if;
  if target = auth.uid() then return 'self'; end if;

  select f.status into existing
  from public.friendships f
  where (f.user_id = auth.uid() and f.friend_id = target)
     or (f.user_id = target and f.friend_id = auth.uid())
  limit 1;

  if existing = 'accepted' then return 'friends'; end if;
  if existing = 'pending' then
    -- They already asked us: treat this click as an accept instead of dead-ending.
    update public.friendships
    set status = 'accepted', accepted_at = now()
    where status = 'pending'
      and ((user_id = auth.uid() and friend_id = target) or (user_id = target and friend_id = auth.uid()));
    return 'friends';
  end if;

  insert into public.friendships (user_id, friend_id) values (auth.uid(), target);
  return 'pending';
end;
$$;

-- Supabase grants EXECUTE on new public-schema functions to anon/authenticated via
-- ALTER DEFAULT PRIVILEGES, so PUBLIC-only revokes are not enough here.
revoke all on function public.add_friend(text) from public, anon;
grant execute on function public.add_friend(text) to authenticated;

create or replace function public.respond_friend(p_friendship_id bigint, p_accept boolean)
returns text
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    return 'unauthorized';
  end if;

  if p_accept then
    update public.friendships
    set status = 'accepted', accepted_at = now()
    where id = p_friendship_id and friend_id = auth.uid() and status = 'pending';
    if found then return 'accepted'; end if;
    return 'forbidden';
  end if;

  delete from public.friendships
  where id = p_friendship_id
    and ((friend_id = auth.uid()) or (user_id = auth.uid()));
  if found then return 'removed'; end if;
  return 'forbidden';
end;
$$;

revoke all on function public.respond_friend(bigint, boolean) from public, anon;
grant execute on function public.respond_friend(bigint, boolean) to authenticated;

