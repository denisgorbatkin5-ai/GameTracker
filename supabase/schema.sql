  price              text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

create index if not exists games_name_idx on public.games (lower(name));

-- --------------------------------------------------------- collection items
create table if not exists public.collection_items (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null references public.profiles (id) on delete cascade,
  game_id      bigint not null references public.games (id) on delete cascade,
  status       text not null default 'backlog'
                 check (status in ('backlog', 'playing', 'completed', 'dropped')),
  rating       int check (rating is null or rating between 0 and 10),
  hours_played numeric(8, 2) check (hours_played is null or hours_played >= 0),
  finished_at  date,
  notes        text,
  is_favorite  boolean not null default false,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (user_id, game_id)
);

create index if not exists collection_items_user_idx on public.collection_items (user_id);
create index if not exists collection_items_game_idx on public.collection_items (game_id);

-- --------------------------------------------------------------- categories
