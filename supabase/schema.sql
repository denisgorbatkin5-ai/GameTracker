  label        text not null,
  color        text not null default '#64748b',
  sort_order   int not null default 0,
  unique (tier_list_id, key)
);

create table if not exists public.tier_items (
  id         bigint generated by default as identity primary key,
  tier_row_id bigint not null references public.tier_rows (id) on delete cascade,
  game_id    bigint not null references public.games (id) on delete cascade,
  position   int not null default 0
);

create index if not exists tier_items_row_idx on public.tier_items (tier_row_id);
create index if not exists tier_items_game_idx on public.tier_items (game_id);

-- ----------------------------------------------------------------- friends
-- One row per directed request. A pair is kept unique by user_id/friend_id and the
-- add_friend() RPC refuses to create the mirrored row, so a pair has at most one edge.
create table if not exists public.friendships (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  friend_id   uuid not null references public.profiles (id) on delete cascade,
  status      text not null default 'pending' check (status in ('pending', 'accepted')),
  created_at  timestamptz not null default now(),
  accepted_at timestamptz,
  unique (user_id, friend_id),
  check (user_id <> friend_id)
);

create index if not exists friendships_user_idx on public.friendships (user_id);
create index if not exists friendships_friend_idx on public.friendships (friend_id);

-- ------------------------------------------------------- profile showcase
-- The "featured shelf" on a profile: a handful of collection games pinned by the owner.
create table if not exists public.profile_showcase (
  user_id    uuid not null references public.profiles (id) on delete cascade,
  game_id    bigint not null references public.games (id) on delete cascade,
  position   int not null default 0,
  created_at timestamptz not null default now(),
  primary key (user_id, game_id)
);

